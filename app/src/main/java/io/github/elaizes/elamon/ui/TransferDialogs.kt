/** The longest passphrase taken: far beyond any typed, short of one pasted by mistake. */
private const val PASSPHRASE_MAX = 1024

/** Windows kept secure, and by how many of what is shown in them: the flag goes when the last does. Main thread only. */
private object SecureWindows {
	private val holds = mutableMapOf<Window, Int>()

	fun hold(window: Window) {
		val n = holds[window] ?: 0
		if (n == 0) window.addFlags(WindowManager.LayoutParams.FLAG_SECURE)
		holds[window] = n + 1
	}

	fun release(window: Window) {
		val n = (holds[window] ?: 1) - 1
		if (n > 0) {
			holds[window] = n
		} else {
			holds.remove(window)
			window.clearFlags(WindowManager.LayoutParams.FLAG_SECURE)
		}
	}
}

/**
 * The activity's window kept out of screenshots, screen recordings and the recent apps
 * (FLAG_SECURE) for as long as this is shown, as a passphrase dialog over it is.
 */
@Composable
private fun SecureWindow() {
	val window = LocalActivity.current?.window
	DisposableEffect(window) {
		window?.let(SecureWindows::hold)
		onDispose { window?.let(SecureWindows::release) }
	}
}

/**
 * Asks for a passphrase. For a new file ([twice]) it is typed twice alike, at least
 * [PairingsFile.PASSPHRASE_MIN] characters long and not obviously easy to guess
 * ([Passphrases.weakness]), or Generate makes one of six random words. The fields use the password
 * keyboard, hide what is typed unless asked to show it, and are never saved: they live in plain
 * `remember`, are emptied as the passphrase is handed on, and go with the dialog, which nothing
 * can capture meanwhile.
 */
@Composable
fun PassphraseDialog(
	title: String,
	text: String,
	twice: Boolean,
	confirmLabel: String,
	onDismiss: () -> Unit,
	onPassphrase: (CharArray) -> Unit,
	error: String? = null,
) {
	SecureWindow()
	val first = remember { TextFieldState() }
	val again = remember { TextFieldState() }
	var shown by remember { mutableStateOf(false) }
	var generated by remember { mutableStateOf(false) }
	DisposableEffect(Unit) {
		onDispose {
			first.clearText()
			again.clearText()
		}
	}
	val weakness = if (twice) Passphrases.weakness(first.text) else null
	val tooShort = weakness == Passphrases.Weakness.TooShort
	// Said once the passphrase is long enough to be judged.
	val weak = weakness != null && !tooShort
	val differ = twice && !first.text.contentEquals(again.text)
	val ready = first.text.isNotEmpty() && weakness == null && !differ
	val submit = {
		if (ready) {
			val typed = first.text
			val chars = CharArray(typed.length) { typed[it] }
			first.clearText()
			again.clearText()
			onPassphrase(chars)
		}
	}
	val mode = if (shown) TextObfuscationMode.Visible else TextObfuscationMode.RevealLastTyped
	val keyboard = { last: Boolean -> KeyboardOptions(keyboardType = KeyboardType.Password, imeAction = if (last) ImeAction.Done else ImeAction.Next) }
	val onDone = KeyboardActionHandler { submit() }
	GlassDialog(
		onDismiss = onDismiss,
		title = title,
		secure = true,
		text = {
			Column(verticalArrangement = Arrangement.spacedBy(Space.m)) {
				Text(text, style = MaterialTheme.typography.bodyMedium)
				OutlinedSecureTextField(
					state = first,
					label = { Text(stringResource(R.string.transfer_passphrase)) },
					textObfuscationMode = mode,
					inputTransformation = InputTransformation.maxLength(PASSPHRASE_MAX),
					trailingIcon = {
						IconToggleButton(checked = shown, onCheckedChange = { shown = it }) {
							Icon(if (shown) ElIcons.Conceal else ElIcons.Reveal, stringResource(R.string.transfer_show))
						}
					},
					isError = error != null || weak || (tooShort && again.text.isNotEmpty()),
					supportingText = when {
						error != null -> {
							{ Text(error, Modifier.semantics { liveRegion = LiveRegionMode.Polite }) }
						}
						weak -> {
							{ Text(stringResource(R.string.transfer_weak), Modifier.semantics { liveRegion = LiveRegionMode.Polite }) }
						}
						twice -> {
							{ Text(pluralStringResource(R.plurals.transfer_too_short, PairingsFile.PASSPHRASE_MIN, PairingsFile.PASSPHRASE_MIN)) }
						}
						else -> null
					},
					keyboardOptions = keyboard(!twice),
					onKeyboardAction = if (twice) null else onDone,
					modifier = Modifier.fillMaxWidth(),
				)
				if (twice) {
					val mismatch = differ && again.text.isNotEmpty()
					OutlinedSecureTextField(
						state = again,
						label = { Text(stringResource(R.string.transfer_passphrase_again)) },
						textObfuscationMode = mode,
						inputTransformation = InputTransformation.maxLength(PASSPHRASE_MAX),
						isError = mismatch,
						supportingText = if (mismatch) {
							{ Text(stringResource(R.string.transfer_differ)) }
						} else {
							null
						},
						keyboardOptions = keyboard(true),
						onKeyboardAction = onDone,
						modifier = Modifier.fillMaxWidth(),
					)
					// Six random words, shown so they can be written down.
					TextButton(onClick = {
						val words = Passphrases.generate()
						first.setTextAndPlaceCursorAtEnd(words)
						again.setTextAndPlaceCursorAtEnd(words)
						shown = true
						generated = true
					}) { Text(stringResource(R.string.transfer_generate)) }
					if (generated) {
						Text(stringResource(R.string.transfer_generated_note), style = MaterialTheme.typography.bodySmall, color = MaterialTheme.colorScheme.onSurfaceVariant)
					}
				}
			}
		},
		confirm = { TextButton(onClick = submit, enabled = ready) { Text(confirmLabel) } },
		dismiss = { TextButton(onClick = onDismiss) { Text(stringResource(R.string.cancel)) } },
	)
}

/** What exporting or importing pairings is doing or came to, over Settings. */
@Composable
fun TransferDialogs(transfer: TransferViewModel) {
	val state by transfer.state.collectAsStateWithLifecycle()
	when (val s = state) {
		Transfer.Idle -> {}
		is Transfer.ExportNeedsPassphrase -> PassphraseDialog(
			title = stringResource(R.string.settings_export),
			text = stringResource(R.string.transfer_export_again),
			twice = true,
			confirmLabel = stringResource(R.string.transfer_export_button),
			onDismiss = { transfer.cancelExport(s.uri) },
			onPassphrase = { transfer.export(s.uri, it) },
		)
		is Transfer.ImportNeedsPassphrase -> PassphraseDialog(
			title = stringResource(R.string.settings_import),
			text = stringResource(R.string.transfer_import_text),
			twice = false,
			confirmLabel = stringResource(R.string.transfer_import_button),
			onDismiss = transfer::dismiss,
			onPassphrase = transfer::importWith,
			error = if (s.wrong) stringResource(R.string.transfer_wrong) else null,
		)
		is Transfer.Working -> Working(
			stringResource(if (s.export) R.string.transfer_encrypting else R.string.transfer_decrypting),
			onCancel = if (s.cancellable) transfer::cancelWork else null,
		)
		is Transfer.ImportConflictAsked -> ConflictDialog(s.conflict, s.index, s.count, onAnswer = transfer::answer)
		is Transfer.Exported -> Outcome(
			stringResource(R.string.transfer_exported_title),
			listOfNotNull(
				pluralStringResource(R.plurals.transfer_exported, s.count, s.count),
				if (s.leftOut > 0) pluralStringResource(R.plurals.transfer_left_out, s.leftOut, s.leftOut) else null,
			),
			transfer::dismiss,
		)
		is Transfer.Imported -> Outcome(
			stringResource(R.string.transfer_imported_title),
			listOfNotNull(
				stringResource(R.string.transfer_imported, s.added, s.replaced),
				if (s.kept > 0) stringResource(R.string.transfer_imported_kept, s.kept) else null,
				if (s.added + s.replaced > 0) stringResource(R.string.transfer_imported_note) else null,
			),
			transfer::dismiss,
		)
		is Transfer.Failed -> Outcome(
			stringResource(if (s.export) R.string.settings_export else R.string.settings_import),
			listOf(stringResource(s.message)),
			transfer::dismiss,
		)
	}
}

/** While the key is made from the passphrase (a second or two, which [onCancel] gives up on), or the pairings saved. */
@Composable
private fun Working(title: String, onCancel: (() -> Unit)?) {
	GlassDialog(
		onDismiss = { onCancel?.invoke() },
		title = title,
		text = {
			Box(Modifier.fillMaxWidth(), contentAlignment = Alignment.Center) { CircularProgressIndicator() }
		},
		confirm = {},
		dismiss = onCancel?.let { cancel -> { TextButton(onClick = cancel) { Text(stringResource(R.string.cancel)) } } },
	)
}

/**
 * A computer the file would put in place of the one here, which it has with another certificate
 * or other addresses: both shown, replaced only on the person's word. Keeping this phone's is the
 * answer to anything else, a tap outside or Back.
 */
@Composable
private fun ConflictDialog(conflict: ImportConflict, index: Int, count: Int, onAnswer: (replace: Boolean) -> Unit) {
	GlassDialog(
		onDismiss = { onAnswer(false) },
		title = stringResource(R.string.transfer_conflict_title, conflict.here.name),
		icon = ElIcons.Laptop,
		text = {
			Column(verticalArrangement = Arrangement.spacedBy(Space.sPlus)) {
				if (count > 1) Text(stringResource(R.string.transfer_conflict_count, index + 1, count), style = MaterialTheme.typography.labelLarge, color = MaterialTheme.colorScheme.onSurfaceVariant)
				Text(stringResource(if (conflict.certificate) R.string.transfer_conflict_certificate else R.string.transfer_conflict_hosts), style = MaterialTheme.typography.bodyMedium)
				Compared(stringResource(R.string.transfer_conflict_here), conflict.here.fingerprint, conflict.here.hosts, conflict.certificate, conflict.hosts)
				Compared(stringResource(R.string.transfer_conflict_file), conflict.incoming.fingerprint, conflict.incoming.hosts, conflict.certificate, conflict.hosts)
			}
		},
		confirm = { TextButton(onClick = { onAnswer(true) }) { Text(stringResource(R.string.transfer_conflict_replace)) } },
		dismiss = { TextButton(onClick = { onAnswer(false) }) { Text(stringResource(R.string.transfer_conflict_keep)) } },
	)
}

/** One side of a [ConflictDialog]: what differs, the certificate's digits as `elamond pair` prints them and the addresses. */
@Composable
private fun Compared(label: String, fingerprint: String, hosts: List<String>, certificate: Boolean, addresses: Boolean) {
	Column(
		Modifier.fillMaxWidth().background(MaterialTheme.colorScheme.surfaceContainerHigh, RoundedCornerShape(Radius.m)).padding(Space.m),
		verticalArrangement = Arrangement.spacedBy(Space.xs),
	) {
		Text(label, style = MaterialTheme.typography.labelLarge, color = MaterialTheme.colorScheme.onSurfaceVariant)
		if (certificate) Text(ElamondClient.prettyFingerprint(fingerprint), fontFamily = FontFamily.Monospace, style = MaterialTheme.typography.bodyMedium)
		if (addresses || !certificate) Text(hosts.joinToString(", "), style = MaterialTheme.typography.bodySmall)
	}
}

@Composable
private fun Outcome(title: String, lines: List<String>, onDismiss: () -> Unit) {
	GlassDialog(
		onDismiss = onDismiss,
		title = title,
		text = {
			Column(verticalArrangement = Arrangement.spacedBy(Space.sPlus)) {
				for (line in lines) Text(line, style = MaterialTheme.typography.bodyMedium)
			}
		},
		confirm = { TextButton(onClick = onDismiss) { Text(stringResource(R.string.settings_close)) } },
	)
}
