/** `text` with `{0}`, `{1}` … replaced by `args`. @param {string} text @param {...unknown} args */
export function fill(text, ...args) {
	return text.replace(/\{(\d+)\}/g, (m, i) => (Number(i) < args.length ? String(args[Number(i)]) : m));
}
